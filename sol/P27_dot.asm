TITLE PGM27: DOT MATRIX MANIPULATION
; CSE 3210 Lab Problem 27 - style of Yu & Marut (Assembly Language Programming)
.MODEL SMALL
.STACK 100H
.DATA
CR EQU 0DH
LF EQU 0AH
; 8x8 bitmap of the letter A (1 = LED on)
PAT DB 00011000B,00100100B,01000010B,01000010B,01111110B,01000010B,01000010B,01000010B
M1 DB 'Original pattern:',0DH,0AH,'$'
M2 DB 0DH,0AH,'Inverted pattern (NOT):',0DH,0AH,'$'
.CODE
MAIN PROC
; initialize DS
 MOV AX,@DATA
 MOV DS,AX
 LEA DX,M1
 MOV AH,9
 INT 21H
 LEA SI,PAT
 CALL SHOWMAT
 MOV CX,8
 LEA SI,PAT
INV:
 NOT BYTE PTR [SI]  ; manipulate: flip every dot
 INC SI
 LOOP INV
 LEA DX,M2
 MOV AH,9
 INT 21H
 LEA SI,PAT
 CALL SHOWMAT
; DOS exit
 MOV AH,4CH
 INT 21H
MAIN ENDP

SHOWMAT PROC          ; SI -> 8 bytes, draws '#' for 1 and '.' for 0
 PUSH AX
 PUSH BX
 PUSH CX
 PUSH DX
 PUSH SI
 MOV CX,8
ROW:
 MOV BL,[SI]
 PUSH CX
 MOV CX,8
COL:
 MOV DL,'.'
 SHL BL,1
 JNC PUT
 MOV DL,'#'
PUT:
 MOV AH,2
 INT 21H
 LOOP COL
 MOV DL,0DH
 INT 21H
 MOV DL,0AH
 INT 21H
 POP CX
 INC SI
 LOOP ROW
 POP SI
 POP DX
 POP CX
 POP BX
 POP AX
 RET
SHOWMAT ENDP
END MAIN
