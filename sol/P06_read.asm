TITLE PGM6: READ CHAR AND DISPLAY ON NEXT LINE
; CSE 3210 Lab Problem 06 - style of Yu & Marut (Assembly Language Programming)
.MODEL SMALL
.STACK 100H
.DATA
CR EQU 0DH
LF EQU 0AH
P1 DB 'Enter a character: $'
.CODE
MAIN PROC
; initialize DS
 MOV AX,@DATA
 MOV DS,AX
 LEA DX,P1
 MOV AH,9
 INT 21H
 MOV AH,1
 INT 21H
 MOV BL,AL
 MOV AH,2
 MOV DL,0DH
 INT 21H
 MOV DL,0AH
 INT 21H
 MOV DL,BL
 INT 21H
; DOS exit
 MOV AH,4CH
 INT 21H
MAIN ENDP
END MAIN
