TITLE PGM19: ROTATE BX 4 POSITIONS LEFT
; CSE 3210 Lab Problem 19 - style of Yu & Marut (Assembly Language Programming)
.MODEL SMALL
.STACK 100H
.DATA
CR EQU 0DH
LF EQU 0AH
M1 DB 'Before: $'
M2 DB 0DH,0AH,'After : $'
.CODE
MAIN PROC
; initialize DS
 MOV AX,@DATA
 MOV DS,AX
 LEA DX,M1
 MOV AH,9
 INT 21H
 MOV BX,1234H
 CALL BINOUT
 MOV CL,4
 ROL BX,CL
 LEA DX,M2
 MOV AH,9
 INT 21H
 CALL BINOUT
; DOS exit
 MOV AH,4CH
 INT 21H
MAIN ENDP

BINOUT PROC           ; prints BX as 16-bit binary (BX preserved)
 PUSH AX
 PUSH BX
 PUSH CX
 PUSH DX
 MOV CX,16
B_TOP:
 MOV DL,'0'
 SHL BX,1
 JNC B_SHOW
 MOV DL,'1'
B_SHOW:
 MOV AH,2
 INT 21H
 LOOP B_TOP
 POP DX
 POP CX
 POP BX
 POP AX
 RET
BINOUT ENDP
END MAIN
